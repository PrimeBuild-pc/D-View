/** Unknown or untrusted text must never reach the UI, even as an error fallback. */
export function localizedError(copy: Dict, error: unknown): string {
  const message = error instanceof Error ? error.message : typeof error === 'string' ? error : '';
  if (Object.hasOwn(copy.errors, message)) return copy.errors[message as ErrorCode];
  if (Object.hasOwn(codesByMessage, message)) return copy.errors[codesByMessage[message]!];
  if (!/[\r\n]/.test(message)) {
    const code = patterns.find(([pattern]) => pattern.test(message))?.[1];
    if (code) return copy.errors[code];
  }
  return copy.errors.REQUEST_FAILED;
}
